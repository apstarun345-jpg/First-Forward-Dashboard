#!/usr/bin/env node
/* Builds the English dictionary files from dev/i18n-en-full.json (the source of truth).
 *   i18n-en.js              core phrases (eager — shell, Home, shared text, short fragments)
 *   i18n-en-<module>.js     phrases used ONLY by one lazy page module; lazy.js loads it with that module
 * A phrase is moved out of core only if it is long (>= 20 chars), found in exactly one lazy module's
 * source and in no eager file / server.js, so a missing chunk can never leave shared text untranslated.
 * Run:  node dev/shard-i18n.js   (after editing dev/i18n-en-full.json)                              */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dict = JSON.parse(fs.readFileSync(path.join(root, 'dev/i18n-en-full.json'), 'utf8'));
const lazySrc = fs.readFileSync(path.join(root, 'lazy.js'), 'utf8');
const files = fs.readdirSync(root).filter((f) => f.endsWith('.js') && !/^i18n|\.test\./.test(f));
const indexHtml = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const eagerNames = new Set([...indexHtml.matchAll(/<script[^>]*\ssrc="\/?([^"?]+)\.js/g)].map((m) => m[1]));
const lazyNames = new Set(files.map((f) => f.replace(/\.js$/, '')).filter((n) => new RegExp(`'${n}'`).test(lazySrc) && !eagerNames.has(n) && n !== 'lazy'));
const src = Object.fromEntries(files.map((f) => [f, fs.readFileSync(path.join(root, f), 'utf8')]));
const variants = (k) => [k, k.replace(/\\/g, '\\\\').replace(/'/g, "\\'"), k.replace(/\\/g, '\\\\').replace(/"/g, '\\"'), k.replace(/`/g, '\\`'), k.replace(/\\/g, '\\\\')];

const core = {}; const chunks = {};
for (const [k, v] of Object.entries(dict)) {
  let target = null;
  if (k.length >= 20) {
    const cands = variants(k);
    const hit = files.filter((f) => cands.some((c) => src[f].includes(c)));
    const lazyHit = hit.filter((f) => lazyNames.has(f.replace(/\.js$/, '')));
    if (hit.length === 1 && lazyHit.length === 1) target = lazyHit[0].replace(/\.js$/, '');
  }
  if (target) (chunks[target] = chunks[target] || {})[k] = v; else core[k] = v;
}
const wrap = (name, obj) => `/* 🌐 English phrases (generated by dev/shard-i18n.js from dev/i18n-en-full.json) — ${name}. Missing phrases fall back to the original text. */
window.FF = window.FF || {};
(function (FF) {
  'use strict';
  if (!FF.i18n || !FF.i18n.extend) return;
  FF.i18n.extend('en', ${JSON.stringify(obj)});
})(window.FF);
`;
for (const f of fs.readdirSync(root)) if (/^i18n-en-.+\.js$/.test(f)) fs.unlinkSync(path.join(root, f));
fs.writeFileSync(path.join(root, 'i18n-en.js'), wrap('core', core));
let moved = 0;
for (const [m, obj] of Object.entries(chunks)) { fs.writeFileSync(path.join(root, `i18n-en-${m}.js`), wrap(m, obj)); moved += Object.keys(obj).length; }
console.log(`core ${Object.keys(core).length} phrases · ${Object.keys(chunks).length} chunks · ${moved} phrases moved`);
